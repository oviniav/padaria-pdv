    private void btnEntrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEntrarActionPerformed
String usuario = txtUsuario.getText().trim();
String senha = new String(txtSenha.getPassword());
if (usuario.isEmpty() || senha.isEmpty()) {
    JOptionPane.showMessageDialog(this, "Informe usuario e senha.", "Login", JOptionPane.WARNING_MESSAGE);
    return;
}
try {
    Funcionario f = new FuncionarioDAO().autenticar(usuario, senha);
    if(f==null) {
        JOptionPane.showMessageDialog(this, "Usuario ou senha invalidos.", "Login", JOptionPane.ERROR_MESSAGE);
        txtSenha.setText("");
        txtSenha.requestFocus();
        return;
    }
    new TelaPrincipal(f).setVisible(true);
    dispose();
} catch (SQLException e) {
    JOptionPane.showMessageDialog(this, "Erro ao acessar o banco: \n" + e.getMessage(), "Erro", JOptionPane.ERROR_MESSAGE);
}
    }//GEN-LAST:event_btnEntrarActionPerformed

